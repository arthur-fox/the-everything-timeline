/**
 * Day 43 (Phase 4c item 3): dated cities for the globe.
 *
 * Hand-curated for this project (public domain, like the nations table): each city has a
 * position, an importance rank, a founding year (approximate for ancient cities: the year it
 * was a town worth naming), an abandonment year where it was deserted, and the name it went by
 * in English at each date, so the map says Byzantium in 500 BCE, Constantinople in 1453 and
 * Istanbul from 1930. Positions are the historic centre (checked against Natural Earth
 * populated places, public domain, where the city still exists: scripts/check-cities.js).
 *
 * Row: C(id, lat, lng, rank, founded, abandoned | null, name, [year, name]…, [options])
 *   rank 1 = world city (shown from orbit) … 4 = regional town (close zoom only)
 *   options: { ranks: [[year, rank], …] } — rank changes over time (Edo/Tokyo, New York …)
 *            { ne: 'Natural Earth name' } — when the current name differs from Natural Earth's
 *            { island: true } — on an island too small for the simplified land shapes (land check)
 */

function C(id, lat, lng, rank, founded, abandoned, ...rest) {
  let opts = {};
  if (rest.length && typeof rest[rest.length - 1] === 'object') opts = rest.pop();
  const names = [{ from: founded, name: rest[0] }];
  for (let i = 1; i + 1 < rest.length; i += 2) names.push({ from: rest[i], name: rest[i + 1] });
  return { id, lat, lng, rank, founded, abandoned, names, ranks: opts.ranks || null, ne: opts.ne || null, island: !!opts.island };
}

