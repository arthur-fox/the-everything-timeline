/**
 * Day 43 (Phase 4c item 3): timeline events pinned to places on the globe.
 * Day 65: country packs pin their own timeline items with 'country:<country id>:<item id>'
 * (e.g. 'country:peru:peru-republic', data/countries/peru.json).
 *
 * Each row points at an existing timeline entry (no new descriptions: clicking a pin opens that
 * entry's detail panel) and says where and when it happened:
 *   P(ref, year, lat, lng, place, label, opts?)
 *     ref   'event:<title>' for the cosmic/world events list, or '<view>:<item id>' for a topic
 *           item (wars, technology, science, religion, philosophy, art, economics, civilisations)
 *     year  the year the pin marks (shown near the slider year; see PIN_WINDOW)
 *     place where, in the English of the time ("Constantinople", "Edo")
 *     label short marker text ("Battle of Waterloo"); the detail panel shows the full entry
 *     opts  { sea: true } for naval battles / voyages, { island: true } for islands too small for
 *           the simplified land shapes (both exempt from the on-land check)
 *
 * Hand-curated (public domain). Positions are the site of the event to ~10 km.
 * scripts/check-cities.js checks every ref resolves, the year is inside the entry's dates (±30),
 * and land pins sit on land.
 */

function P(ref, year, lat, lng, place, label, opts = {}) {
  return { ref, year, lat, lng, place, label, sea: !!opts.sea, island: !!opts.island };
}

/** How far (years) from the slider year a pin is shown: wider in deep time, tight in the 20th c. */
export function pinWindow(year) {
  if (year < -1000) return 300;
  if (year < 0) return 100;
  if (year < 1000) return 50;
  if (year < 1500) return 30;
  if (year < 1800) return 20;
  if (year < 1900) return 10;
  return 5;
}

